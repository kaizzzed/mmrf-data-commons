import { createHash } from 'crypto';
import { readFileSync } from 'fs';
import path from 'path';
import { canonicalJson, pinnedFromVizSpec, pinnedHash } from '../viz/ppPinnedArgs';
import { createThread, threadReducer, type ThreadState } from './reducer';
import { createSseParser } from './sseParser';
import {
  ACTION_STATUSES,
  ANALYSIS_KINDS,
  APP_IDS,
  FINGERPRINT_SCHEMA,
  FROZEN_ROWS_CAP,
  LEASED_STATUSES,
  PENDING_KIND_BY_STATUS,
  SNAPSHOT_LIMIT_BYTES,
  SYNTHETIC_NOTICE,
  WAITING_STATUSES,
  type AguiEvent,
  type ConfirmPending,
  type JsonValue,
  type OrionActionName,
  type PinnedViz,
  type RunAgentInput,
  type RunRecord,
  type RunView,
  type SaveCohortsArgs,
  type Segment,
  type WaitingStatus,
} from './types';

/**
 * The v1.2 contract fixtures (orion/contracts/fixtures in the sandbox repo, generated by
 * build_fixtures.py and copied here byte for byte): every stream parses, replays through the
 * reducer to the status it names, and cites only facts it carries.
 */
const DIR = path.join(__dirname, '__fixtures__');
const VIZ_DIR = path.join(__dirname, '..', 'viz', '__fixtures__');

const STREAMS = {
  'j1-stub': 'ObservedOnly',
  'j1-complete': 'Complete',
  'j1-partial': 'Partial',
  'j1-retry': 'Complete',
  'j1-stop': 'Cancelled',
  'j2-save-pause': 'AwaitingConfirmation',
  'j2-after-confirm': 'Complete',
  'j2-dont-save': 'Complete',
  'j3-save-pause': 'AwaitingConfirmation',
  'j3-after-confirm': 'Complete',
  'j3-edit-at-pause': 'AwaitingConfirmation',
  'j3-dont-save': 'Complete',
  'j3-deinput': 'Complete',
  oncomatrix: 'Complete',
  clarify: 'Clarifying',
  consent: 'AwaitingConsent',
  interrupted: 'Unsupported',
  'cancel-waiting': 'Clarifying',
} as const;
type StreamName = keyof typeof STREAMS;
const NAMES = Object.keys(STREAMS) as StreamName[];

/** Streams that continue a run another fixture left paused or ended. */
const PREDECESSOR: Partial<Record<StreamName, StreamName>> = {
  'j2-after-confirm': 'j2-save-pause',
  'j3-after-confirm': 'j3-save-pause',
  'j1-retry': 'j1-partial',
};

const readText = (name: string, dir = DIR): string => readFileSync(path.join(dir, name), 'utf8');

const eventsOf = (name: StreamName): AguiEvent[] =>
  createSseParser()
    .push(new Uint8Array(readFileSync(path.join(DIR, `${name}.events.jsonl`))))
    .map((item) => {
      if (item.kind !== 'event') throw new Error(`${name}: ${item.error.message}`);
      return item.event;
    });

const viewsOf = (events: AguiEvent[]): RunView[] =>
  events.flatMap((e) => (e.type === 'STATE_SNAPSHOT' ? [e.snapshot] : []));

/** The invocation's run: RUN_STARTED names it (a stream may report an earlier run first). */
const runIdOf = (events: AguiEvent[]): string => {
  const started = events[0];
  if (started.type !== 'RUN_STARTED') throw new Error('a stream starts with RUN_STARTED');
  return started.runId;
};

const segmentsOf = (view: RunView): Segment[] => [
  ...[...view.observed, ...(view.interpretation ?? []), ...(view.hypotheses ?? [])].flatMap((s) => s.segments),
  ...view.limitations.flatMap((l) => l.segments ?? []),
  ...view.vizSpecs.flatMap((spec) => [...(spec.frozen?.rows.flat() ?? []), ...(spec.frozen?.note ?? [])]),
];

const citedFactIds = (view: RunView): string[] => [
  ...segmentsOf(view).flatMap((s) => (s.factId ? [s.factId] : [])),
  ...[...(view.interpretation ?? []), ...(view.hypotheses ?? [])].flatMap((s) => s.cites ?? []),
  ...view.cohorts.flatMap((c) => (c.caseCountFactId ? [c.caseCountFactId] : [])),
  ...(view.pending?.kind === 'confirm'
    ? view.pending.cohorts.flatMap((c) => [c.caseCountFactId, c.eligibleCountFactId].flatMap((id) => (id ? [id] : [])))
    : []),
];

const isWaiting = (status: string): status is WaitingStatus =>
  (WAITING_STATUSES as readonly string[]).includes(status);

const replay = (events: AguiEvent[], state?: ThreadState): ThreadState =>
  events.reduce(threadReducer, state ?? createThread(viewsOf(events)[0].threadId));

const replayWithPredecessor = (name: StreamName): ThreadState => {
  const before = PREDECESSOR[name];
  return replay(eventsOf(name), before ? replayWithPredecessor(before) : undefined);
};

describe('contract fixtures', () => {
  it.each(NAMES)('%s replays to the status it names, frame by frame', (name) => {
    const text = readText(`${name}.events.jsonl`);
    for (const frame of text.split('\n\n').filter(Boolean)) {
      expect(Buffer.byteLength(`${frame}\n\n`, 'utf8')).toBeLessThanOrEqual(SNAPSHOT_LIMIT_BYTES);
    }
    const events = eventsOf(name);
    const state = replayWithPredecessor(name);
    const runId = runIdOf(events);
    expect(state.runs[runId].status).toBe(STREAMS[name]);
    expect(state.runs[runId].flags).toEqual([]);
    expect(state.flags).toEqual([]);
    expect(state.invocation?.terminal).toBe(true);
  });

  it.each(NAMES)('%s carries pending only while waiting, and cites facts it carries', (name) => {
    for (const view of viewsOf(eventsOf(name))) {
      const expected = isWaiting(view.status) ? PENDING_KIND_BY_STATUS[view.status] : null;
      expect(view.pending?.kind ?? null).toBe(expected);
      expect(view.notice).toBe(SYNTHETIC_NOTICE);
      const facts = new Map(view.facts.map((f) => [f.id, f]));
      expect(citedFactIds(view).filter((id) => !facts.has(id))).toEqual([]);
      const refs = new Set(view.cohorts.map((c) => c.ref));
      for (const spec of view.vizSpecs) expect(spec.cohortRefs.filter((r) => !refs.has(r))).toEqual([]);
      for (const followUp of view.followUps) expect(ANALYSIS_KINDS).toContain(followUp.kind);
      for (const link of view.openLinks) expect(APP_IDS).toContain(link.appId);
      for (const spec of view.vizSpecs) expect(spec.frozen?.rows.length ?? 0).toBeLessThanOrEqual(FROZEN_ROWS_CAP);
      for (const step of view.steps) expect(step.reusedFrom !== null).toBe(step.status === 'Reused');
      const waiting = view.steps.filter((s) => s.status === 'AwaitingUser').map((s) => s.id);
      expect(waiting).toEqual(view.pending?.kind === 'confirm' ? [view.pending.stepId] : []);
      expect(['L', 'A', 'H']).toContain(view.environment.mode);
    }
  });

  it.each(['j2-save-pause', 'j3-save-pause', 'j3-edit-at-pause'] as const)(
    "%s collects the save_cohorts args, which equal the pause snapshot's pending payload",
    (name) => {
      const events = eventsOf(name);
      const state = replay(events);
      const views = viewsOf(events);
      const pause = views[views.length - 1];
      const pending = pause.pending as ConfirmPending;
      const [call] = state.runs[pause.runId].toolCalls;
      expect(call).toMatchObject({ id: pending.nonce, name: 'save_cohorts', ended: true });
      const args = JSON.parse(call.args) as SaveCohortsArgs;
      expect(args).toEqual(pending);
      expect(args.cohorts.every((c) => c.definition !== null && c.defSha256.length === 64)).toBe(true);
      expect(args.cohorts.every((c) => c.caseCountFactId !== null)).toBe(true);
      expect(pause.steps.find((s) => s.id === pending.stepId)?.status).toBe('AwaitingUser');
    },
  );

  it('shows Observed and the chart before the model text (Answering, then Complete)', () => {
    for (const name of NAMES.filter((n) => STREAMS[n] === 'Complete')) {
      const views = viewsOf(eventsOf(name));
      const answering = views.filter((v) => v.status === 'Answering');
      expect(answering).toHaveLength(1);
      expect(answering[0].observed.length).toBeGreaterThan(0);
      expect(answering[0].interpretation).toBeNull();
      const complete = views[views.length - 1];
      expect(complete.interpretation?.length).toBeGreaterThan(0);
      expect(complete.interpretation?.every((s) => (s.cites ?? []).length > 0)).toBe(true);
      expect(complete.followUps.length).toBeGreaterThan(0);
    }
  });

  it("recomputes every carried viz spec's pinnedHash, which matches the request-side hash", async () => {
    let checked = 0;
    for (const name of NAMES) {
      for (const view of viewsOf(eventsOf(name))) {
        for (const spec of view.vizSpecs) {
          expect(spec.requestPinnedHash).toBe(spec.pinnedHash);
          if (spec.pinned === null) continue;
          expect(await pinnedHash(pinnedFromVizSpec(spec))).toBe(spec.pinnedHash);
          checked += 1;
        }
      }
    }
    expect(checked).toBeGreaterThan(0);
  });

  it('drops pinned inputs from a trimmed snapshot, which the card reads from the view route', () => {
    const specs = viewsOf(eventsOf('j3-deinput')).flatMap((v) => v.vizSpecs);
    expect(specs.length).toBeGreaterThan(0);
    for (const spec of specs) {
      expect([spec.launcher, spec.pinned]).toEqual(['deInput', null]);
      expect(() => pinnedFromVizSpec(spec)).toThrow('view route');
    }
  });

  it('reports an earlier run of the thread first, then streams the invocation\'s run', () => {
    for (const [name, status] of [['interrupted', 'Interrupted'], ['cancel-waiting', 'Cancelled']] as const) {
      const events = eventsOf(name);
      const [first, ...rest] = viewsOf(events);
      expect(first.runId).not.toBe(runIdOf(events));
      expect([first.status, first.pending]).toEqual([status, null]);
      expect(rest.every((v) => v.runId === runIdOf(events))).toBe(true);
      expect(replay(events).runs[first.runId].status).toBe(status);
    }
  });

  it('marks an edit: version 2, superseded version 1, reused steps and a new nonce', () => {
    const [first, ...rest] = viewsOf(eventsOf('j3-edit-at-pause'));
    const paused = viewsOf(eventsOf('j3-save-pause')).pop() as RunView;
    expect([first.status, first.plan?.version, first.superseded.map((s) => s.planVersion)]).toEqual(['Executing', 2, [1]]);
    expect(first.steps.filter((s) => s.status === 'Reused').map((s) => s.reusedFrom)).toEqual(
      ['s1', 's2', 's3', 's4', 's5', 's6', 's7'].map((stepId) => ({ planVersion: 1, stepId })),
    );
    const last = rest[rest.length - 1];
    expect((last.pending as ConfirmPending).nonce).not.toBe((paused.pending as ConfirmPending).nonce);
  });

  it('leases a Stopping run, so an expired one is shown Cancelled rather than Stopping forever', () => {
    expect(LEASED_STATUSES).toContain('Stopping');
  });
});

describe('request examples', () => {
  const { examples } = JSON.parse(readText('request-examples.json')) as {
    examples: { name: string; body: RunAgentInput }[];
  };

  it('covers every action with all seven RunAgentInput fields', () => {
    const actions = new Set<OrionActionName>();
    for (const { body } of examples) {
      expect(Object.keys(body).sort()).toEqual(
        ['context', 'forwardedProps', 'messages', 'runId', 'state', 'threadId', 'tools'],
      );
      expect(body.threadId).toMatch(/^[0-9a-f]{32}$/);
      expect(body.runId).toMatch(/^[0-9a-f]{32}$/);
      actions.add(body.forwardedProps.orion.action);
    }
    const resumable = Object.keys(ACTION_STATUSES) as OrionActionName[];
    expect([...actions].sort()).toEqual([...resumable, 'ask', 'warmup'].sort());
  });

  it('carries viz reports only for runs of its own thread', () => {
    const threadOf = new Map<string, string>();
    for (const name of NAMES) for (const view of viewsOf(eventsOf(name))) threadOf.set(view.runId, view.threadId);
    let reports = 0;
    for (const { body } of examples) {
      for (const report of body.forwardedProps.orion.vizReports ?? []) {
        expect(threadOf.get(report.runId)).toBe(body.threadId);
        reports += 1;
      }
    }
    expect(reports).toBeGreaterThan(0);
  });
});

describe('run record examples', () => {
  const RECORDS = {
    'run-record.j1-complete.json': 'j1-complete',
    'run-record.j1-retry.json': 'j1-retry',
  } as const;

  it.each(Object.entries(RECORDS))("%s's stored view is the stream's last snapshot", (file, stream) => {
    const record = JSON.parse(readText(file)) as RunRecord;
    expect(record.schema).toBe('orion.run-record/v1');
    const views = viewsOf(eventsOf(stream as StreamName));
    expect(record.runView).toEqual(views[views.length - 1]);
    expect(record.lease).toBeNull();
    expect(record.runView?.environment.fingerprintSha256).toBe(record.environment.fingerprintSha256);
  });

  it.each(Object.keys(RECORDS))('%s ties every fact to the call and hashes that produced it', (file) => {
    const record = JSON.parse(readText(file)) as RunRecord;
    const calls = new Map(record.calls.map((c) => [c.callId, c]));
    expect(calls.size).toBe(record.calls.length);
    for (const call of record.calls) {
      expect(call.callId.startsWith(`${record.runId}.v${call.planVersion}.${call.stepId}.c`)).toBe(true);
    }
    for (const fact of record.facts) {
      const call = calls.get(fact.callId);
      expect(call?.status).toBe('ok');
      expect([fact.stepId, fact.requestSha256, fact.responseSha256]).toEqual([
        call?.stepId,
        call?.requestSha256,
        call?.responseSha256,
      ]);
    }
    expect(record.planHistory.map((h) => h.version)).toEqual(record.planVersions.map((p) => p.version));
  });

  it('numbers every attempt of a retried step', () => {
    const record = JSON.parse(readText('run-record.j1-retry.json')) as RunRecord;
    const s4 = record.calls.filter((c) => c.stepId === 's4').map((c) => [c.callId.split('.').pop(), c.attempt, c.status]);
    expect(s4).toEqual([['c1', 1, 'error'], ['c2', 2, 'error'], ['c3', 1, 'ok']]);
  });
});

describe('viz vectors', () => {
  const sha256 = (text: string): string => createHash('sha256').update(text, 'utf8').digest('hex');

  it('reproduces the fixture fingerprint with the same canonical JSON', () => {
    const { vectors } = JSON.parse(readText('fingerprint-vectors.json', VIZ_DIR)) as {
      vectors: { name: string; document: JsonValue; canonical: string; sha256: string }[];
    };
    for (const vector of vectors) {
      expect((vector.document as { schema: string }).schema).toBe(FINGERPRINT_SCHEMA);
      expect(canonicalJson(vector.document)).toBe(vector.canonical);
      expect(sha256(vector.canonical)).toBe(vector.sha256);
    }
    expect(vectors[0].sha256).toBe(vectors[1].sha256);
  });

  it('hashes every request-derived pinned form to its requestPinnedHash', async () => {
    const { vectors } = JSON.parse(readText('request-pinned-vectors.json', VIZ_DIR)) as {
      vectors: { name: string; launcher: string; pinned: PinnedViz; requestPinnedHash: string }[];
    };
    expect(new Set(vectors.map((v) => v.launcher))).toEqual(new Set(['survival', 'oncomatrix', 'deDirect', 'deInput']));
    for (const vector of vectors) {
      expect(vector.pinned.kind).toBe(vector.launcher);
      expect(await pinnedHash(vector.pinned)).toBe(vector.requestPinnedHash);
    }
  });
});
